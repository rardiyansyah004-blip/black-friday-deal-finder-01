export function discountPct(d) {
  return Math.round((1 - d.price / d.was) * 100);
}
export function saved(d) {
  return +(d.was - d.price).toFixed(2);
}
/** % the sale price sits below the 90-day typical street price (0 = no real cut). */
export function belowTypicalPct(d) {
  return Math.max(0, Math.round((1 - d.salePrice / d.typicalStreetPrice) * 100));
}
/** Real dollars saved vs the typical street price — the honest saving. */
export function realSaved(d) {
  return +Math.max(0, d.typicalStreetPrice - d.salePrice).toFixed(2);
}
export function money(n) {
  return "$" + n.toLocaleString("en-US", { minimumFractionDigits: n % 1 ? 2 : 0, maximumFractionDigits: 2 });
}

/**
 * Check your own deal: given a sale price, the store's claimed "was" price
 * and the usual (typical street) price, return the Friday Proof verdict.
 * Pure function — used by the checker page and nothing else. No network.
 * Returns null until all three inputs are positive numbers.
 */
export function checkDeal(sale, was, usual) {
  if (![sale, was, usual].every((n) => Number.isFinite(n) && n > 0)) return null;
  const pctBelow = Math.max(0, Math.round((1 - sale / usual) * 100));
  const inflatedWas = was > usual * 1.15;
  const inflatedByPct = inflatedWas ? Math.round((was / usual - 1) * 100) : 0;
  const realSave = +(Math.max(0, usual - sale)).toFixed(2);
  let verdict, verdictLabel, note;
  if (sale >= usual * 0.995) {
    verdict = "skip";
    verdictLabel = "SKIP — NOT A DEAL";
    note = "You would pay the usual price. The sale price matches what this product normally costs — the discount is only on paper.";
  } else if (sale >= usual * 0.9) {
    verdict = "routine";
    verdictLabel = "ROUTINE SALE";
    note = "A real cut, but a small one — only " + pctBelow + "% below the usual price. Buy it if you need it today, not because it's rare.";
  } else {
    verdict = "strong";
    verdictLabel = "STRONG DEAL";
    note = "A genuine cut — " + pctBelow + "% below the usual price, saving " + money(realSave) + ". Worth buying now.";
  }
  if (inflatedWas) {
    note += " And the claimed 'was' price is " + inflatedByPct + "% above the usual price — inflated, so ignore the big % off.";
  }
  return { pctBelow, inflatedWas, inflatedByPct, realSave, verdict, verdictLabel, note };
}
